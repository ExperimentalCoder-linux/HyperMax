-- Tests for version-independent first-run state and independent tutorial tracks.
local Test = require("tests.testlib")
local Tutorial = require("hypermax.tutorial")

local original_path = Tutorial.storage_path
local test_root = vim.fn.fnamemodify(vim.fn.tempname(), ":p")
Tutorial.storage_path = test_root .. "/hypermax/tutorial_progress.json"
Tutorial.Reset_Cache()

Test.Run("Tutorial provides separate Essentials and Advanced lesson lists", function()
	local essentials = Tutorial.Get_Lessons("essentials")
	local advanced = Tutorial.Get_Lessons("advanced")
	Test.True(#essentials > 0)
	Test.True(#advanced > 0)
	Test.Equal("welcome", essentials[1].id)
	Test.Not_Equal(essentials[1].id, advanced[1].id)
	Test.True(essentials[1].title ~= advanced[1].title)
end)

Test.Run("Tutorial first-run marker persists independently of plugin version", function()
	Test.False(Tutorial.First_Run_Completed())
	local ok, err = Tutorial.Mark_First_Run_Completed()
	Test.True(ok, tostring(err))
	Tutorial.Reset_Cache()
	Test.True(Tutorial.First_Run_Completed())
	local file = assert(io.open(Tutorial.storage_path, "rb"))
	local encoded = file:read("*a")
	file:close()
	local data = vim.json.decode(encoded)
	Test.True(data.first_run_completed)
	Test.Nil(data.version, "First-run state must not be keyed to a plugin version")
end)

Test.Run("Tutorial first startup opens the welcome lesson once", function()
	vim.fn.delete(Tutorial.storage_path)
	Tutorial.Reset_Cache()
	Test.False(Tutorial.First_Run_Completed())
	Test.True(Tutorial.Startup_Check())
	Test.True(Tutorial.First_Run_Completed())
	local state = Tutorial.Get_State()
	Test.Equal("lesson", state.view)
	local first_window = state.window
	Test.False(Tutorial.Startup_Check(), "A later startup check must not replay onboarding")
	Test.Equal(first_window, Tutorial.Get_State().window, "The existing tutorial window should not be replaced")
	Tutorial.Close()
end)

Test.Run("Tutorial Essentials and Advanced completion are independent", function()
	local ok, err = Tutorial.Set_Completed("essentials", "welcome", true)
	Test.True(ok, tostring(err))
	Test.True(Tutorial.Is_Completed("essentials", "welcome"))
	Test.False(Tutorial.Is_Completed("advanced", "layouts"))
	local essential_done, essential_total = Tutorial.Get_Progress("essentials")
	local advanced_done = Tutorial.Get_Progress("advanced")
	Test.Equal(1, essential_done)
	Test.True(essential_total > 1)
	Test.Equal(0, advanced_done)
	local reset, reset_error = Tutorial.Reset_Progress("advanced")
	Test.True(reset, tostring(reset_error))
	Test.True(Tutorial.Is_Completed("essentials", "welcome"))
	Test.True(Tutorial.First_Run_Completed())
end)

Test.Run("Tutorial resetting one track leaves the other track and onboarding marker intact", function()
	local ok, err = Tutorial.Set_Completed("advanced", "layouts", true)
	Test.True(ok, tostring(err))
	ok, err = Tutorial.Reset_Progress("essentials")
	Test.True(ok, tostring(err))
	Test.False(Tutorial.Is_Completed("essentials", "welcome"))
	Test.True(Tutorial.Is_Completed("advanced", "layouts"))
	Test.True(Tutorial.First_Run_Completed())
	local invalid = Tutorial.Reset_Progress("unknown")
	Test.False(invalid)
end)

Test.Run("Tutorial menu presents Essentials and Advanced as separate choices", function()
	local opened = Tutorial.Open_Menu()
	Test.True(opened)
	local state = Tutorial.Get_State()
	Test.True(state.window ~= nil and vim.api.nvim_win_is_valid(state.window))
	local lines = vim.api.nvim_buf_get_lines(state.buffer, 0, -1, false)
	local joined = table.concat(lines, "\n")
	Test.True(joined:find("ESSENTIALS", 1, true) ~= nil)
	Test.True(joined:find("ADVANCED", 1, true) ~= nil)

	Tutorial.Open_Category("essentials")
	state = Tutorial.Get_State()
	lines = vim.api.nvim_buf_get_lines(state.buffer, 0, -1, false)
	joined = table.concat(lines, "\n")
	Test.True(joined:find("Projects and the dashboard", 1, true) ~= nil)
	Test.False(joined:find("Reusable project layouts", 1, true) ~= nil)

	Tutorial.Open_Category("advanced")
	state = Tutorial.Get_State()
	lines = vim.api.nvim_buf_get_lines(state.buffer, 0, -1, false)
	joined = table.concat(lines, "\n")
	Test.True(joined:find("Reusable project layouts", 1, true) ~= nil)
	Test.False(joined:find("Projects and the dashboard", 1, true) ~= nil)

	Tutorial.Open_Lesson("essentials", "welcome")
	state = Tutorial.Get_State()
	lines = vim.api.nvim_buf_get_lines(state.buffer, 0, -1, false)
	joined = table.concat(lines, "\n")
	Test.True(joined:find("HyperMax adds project tools", 1, true) ~= nil)
	Tutorial.Close()
end)

Tutorial.storage_path = original_path
Tutorial.Reset_Cache()
pcall(vim.fn.delete, test_root, "rf")
